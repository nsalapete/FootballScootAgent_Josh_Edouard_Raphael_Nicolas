def canonical_name(name: str) -> str:
    """Fold a known alternative spelling to the name kept in the graph ('Türkiye' -> 'Turkey')."""
    return ALIASES.get(name, name)


def country_code(name: str | None) -> str | None:
    """Code of a Transfermarkt country name; an unknown name is kept as its own code, a missing one gives None."""
    if not name:
        return None
    name = canonical_name(name)
    return CODES.get(name, name)
